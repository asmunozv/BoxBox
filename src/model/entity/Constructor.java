package model.entity;

public class Constructor {

    private Integer idConstructor;
    private String ergastConstructorId;
    private String name;
    private String country;

    public Integer getIdConstructor() {
        return idConstructor;
    }

    public void setIdConstructor(Integer idConstructor) {
        this.idConstructor = idConstructor;
    }

    public String getErgastConstructorId() {
        return ergastConstructorId;
    }

    public void setErgastConstructorId(String ergastConstructorId) {
        this.ergastConstructorId = ergastConstructorId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCountry() {
        return country;
    }

    public void setCountry(String country) {
        this.country = country;
    }
}
